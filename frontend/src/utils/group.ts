/**
 * 群成员状态的纯函数判据。
 *
 * 为什么单独一个模块：这条规则（**不在群**的判定与文案）在群信息面板、
 * 联系人卡片上都要用，而它是「票号」语义的直接体现 ——
 * 分散在各组件里各写一遍，分叉之后会表现为「面板说已退出、卡片说不在群」。
 *
 * 判据只看后端算好的 `active`，**不**在本地重算票号：后端才是权威，
 * 前端重算一遍就又多出一份可能不一致的真相。
 */
import type { GroupMember } from '../api/types'

/**
 * 不在群时的状态文案；仍在群时返回空串（调用方据此决定要不要渲染标签）。
 *
 * 方向是刻意选的：在群时给「在群」标签只是噪音（面板里绝大多数人都在群），
 * 只有异常的那几个人值得占一行字。
 */
export function memberStateLabel(m: GroupMember): string {
  if (m.active) return ''
  // 「是谁撕的票」决定文案：群主撕 = 被移出，本人撕 = 主动退出。
  if (m.kickSeq > 0 && m.kickSeq >= m.admitSeq) return '已移出'
  if (m.leftSeq > 0 && m.leftSeq >= m.admitSeq) return '已退出'
  // 票号都在但推不出原因（例如刚出但记录未同步）：给一个中性说法，
  // 不要瞎猜成「已退出」—— 那会冤枉一个其实是被移出的人。
  return '不在群'
}
